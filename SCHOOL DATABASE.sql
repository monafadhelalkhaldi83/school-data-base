-- ---------------------------------------------------------------------
-- 2. إنشاء الجداول المطلوبة
-- ---------------------------------------------------------------------

-- إنشاء جدول الطلاب
CREATE TABLE students (
    id INT PRIMARY KEY,
    student_name VARCHAR(100),
    birth_date DATE,
    gender CHAR(1), -- 'F' أو 'M'
    enrollment_date DATE,
    email VARCHAR(100),
    grade_level INT, -- من 1 إلى 6
    track VARCHAR(50), -- علمي أو انساني
    gpa DECIMAL(5,2) -- المعدل من 100
);

-- إنشاء جدول المعلمين
CREATE TABLE teachers (
    id INT PRIMARY KEY,
    teacher_name VARCHAR(100),
    birth_date DATE,
    gender CHAR(1),
    email VARCHAR(100),
    office_number VARCHAR(20)
);

-- إنشاء جدول المواد
CREATE TABLE subjects (
    id INT PRIMARY KEY,
    subject_name VARCHAR(100)
);

